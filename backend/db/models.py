"""
SQLAlchemy ORM models for persistent storage.
Uses SQLite via aiosqlite for async operations.
"""
from __future__ import annotations

import uuid
from datetime import datetime, timezone
from typing import Optional

from sqlalchemy import (
    Boolean, Column, DateTime, Float, ForeignKey,
    Integer, String, Text, Index
)
from sqlalchemy.orm import declarative_base, relationship

Base = declarative_base()


def utcnow() -> datetime:
    return datetime.now(timezone.utc)


def new_uuid() -> str:
    return str(uuid.uuid4())


class Transaction(Base):
    """
    Stores transaction records processed by the system.
    Features are from the Kaggle European credit card dataset
    (V1-V28 are PCA-transformed; original features are not stored).
    """
    __tablename__ = "transactions"

    id = Column(String(36), primary_key=True, default=new_uuid)
    external_id = Column(String(64), unique=True, nullable=True, index=True)
    time_seconds = Column(Float, nullable=True)   # 'Time' feature
    amount = Column(Float, nullable=True)          # 'Amount' feature
    # V1-V28 stored as JSON text to keep schema flexible
    features_json = Column(Text, nullable=True)
    # Source: 'simulation', 'api', 'batch'
    source = Column(String(32), default="api", nullable=False)
    created_at = Column(DateTime(timezone=True), default=utcnow, nullable=False)

    predictions = relationship("Prediction", back_populates="transaction", cascade="all, delete-orphan")
    alerts = relationship("Alert", back_populates="transaction", cascade="all, delete-orphan")

    __table_args__ = (
        Index("ix_transactions_created_at", "created_at"),
        Index("ix_transactions_source", "source"),
    )


class Prediction(Base):
    """
    Stores model prediction output for each transaction.
    Keeps fraud probability separate from business risk score.
    """
    __tablename__ = "predictions"

    id = Column(String(36), primary_key=True, default=new_uuid)
    transaction_id = Column(String(36), ForeignKey("transactions.id", ondelete="CASCADE"), nullable=False)
    model_version_id = Column(String(36), ForeignKey("model_versions.id"), nullable=True)

    # Supervised fraud classifier output
    predicted_class = Column(Integer, nullable=True)   # 0 or 1
    fraud_probability = Column(Float, nullable=True)   # 0.0-1.0 if model supports it
    # Risk category derived from thresholds (policy-based, not a calibrated probability)
    risk_category = Column(String(16), nullable=True)  # LOW, MEDIUM, HIGH

    # Anomaly detection output (separate from fraud classifier)
    anomaly_score = Column(Float, nullable=True)       # IsolationForest score
    is_anomalous = Column(Boolean, nullable=True)

    # SHAP explanation (stored as JSON)
    explanation_json = Column(Text, nullable=True)

    prediction_latency_ms = Column(Float, nullable=True)
    created_at = Column(DateTime(timezone=True), default=utcnow, nullable=False)

    transaction = relationship("Transaction", back_populates="predictions")
    model_version = relationship("ModelVersion", back_populates="predictions")

    __table_args__ = (
        Index("ix_predictions_transaction_id", "transaction_id"),
        Index("ix_predictions_risk_category", "risk_category"),
        Index("ix_predictions_created_at", "created_at"),
    )


class Alert(Base):
    """
    Fraud alerts generated by the prediction engine.
    Distinguishes model-generated alerts from confirmed fraud incidents.
    """
    __tablename__ = "alerts"

    id = Column(String(36), primary_key=True, default=new_uuid)
    transaction_id = Column(String(36), ForeignKey("transactions.id", ondelete="CASCADE"), nullable=False)
    prediction_id = Column(String(36), ForeignKey("predictions.id"), nullable=True)

    # PENDING, ACKNOWLEDGED, RESOLVED, DISMISSED
    status = Column(String(32), default="PENDING", nullable=False)
    severity = Column(String(16), nullable=False)  # HIGH, CRITICAL
    # Reason: 'high_fraud_probability', 'anomaly_detected', 'both'
    alert_reason = Column(String(64), nullable=False)
    # Human reviewer notes - not pre-populated
    review_notes = Column(Text, nullable=True)
    # IMPORTANT: 'SUSPECTED' means model output only, NOT confirmed fraud
    confirmed_fraud = Column(Boolean, nullable=True)  # None=unknown, True/False=verified

    created_at = Column(DateTime(timezone=True), default=utcnow, nullable=False)
    updated_at = Column(DateTime(timezone=True), default=utcnow, onupdate=utcnow, nullable=False)

    transaction = relationship("Transaction", back_populates="alerts")

    __table_args__ = (
        Index("ix_alerts_status", "status"),
        Index("ix_alerts_severity", "severity"),
        Index("ix_alerts_created_at", "created_at"),
    )


class ModelVersion(Base):
    """
    Tracks trained model versions and their evaluation results.
    """
    __tablename__ = "model_versions"

    id = Column(String(36), primary_key=True, default=new_uuid)
    model_name = Column(String(64), nullable=False)        # e.g. "RandomForest"
    version_tag = Column(String(32), nullable=False)       # e.g. "v1.0"
    is_active = Column(Boolean, default=False, nullable=False)
    artifact_path = Column(String(512), nullable=True)     # path to .pkl file
    preprocessor_path = Column(String(512), nullable=True)
    feature_schema_json = Column(Text, nullable=True)      # expected features in order

    # Dataset metadata
    dataset_name = Column(String(128), nullable=True)
    dataset_rows = Column(Integer, nullable=True)
    fraud_rate = Column(Float, nullable=True)

    # Training config
    random_seed = Column(Integer, nullable=True)
    training_config_json = Column(Text, nullable=True)
    trained_at = Column(DateTime(timezone=True), default=utcnow, nullable=False)

    # Evaluation metrics (test set only — clearly labelled)
    test_accuracy = Column(Float, nullable=True)
    test_precision = Column(Float, nullable=True)
    test_recall = Column(Float, nullable=True)
    test_f1 = Column(Float, nullable=True)
    test_roc_auc = Column(Float, nullable=True)
    test_pr_auc = Column(Float, nullable=True)
    test_fpr = Column(Float, nullable=True)
    training_duration_seconds = Column(Float, nullable=True)
    inference_latency_ms = Column(Float, nullable=True)

    # Full comparison JSON (all models)
    comparison_json = Column(Text, nullable=True)
    selection_rationale = Column(Text, nullable=True)

    predictions = relationship("Prediction", back_populates="model_version")


class TrainingRun(Base):
    """
    Records each training job execution.
    """
    __tablename__ = "training_runs"

    id = Column(String(36), primary_key=True, default=new_uuid)
    status = Column(String(32), default="QUEUED", nullable=False)  # QUEUED, RUNNING, DONE, FAILED
    progress_percent = Column(Float, default=0.0, nullable=False)
    current_stage = Column(String(128), nullable=True)
    error_message = Column(Text, nullable=True)
    model_version_id = Column(String(36), nullable=True)
    started_at = Column(DateTime(timezone=True), nullable=True)
    completed_at = Column(DateTime(timezone=True), nullable=True)
    created_at = Column(DateTime(timezone=True), default=utcnow, nullable=False)


class AppSetting(Base):
    """
    Persistent application settings (key-value store).
    """
    __tablename__ = "app_settings"

    key = Column(String(128), primary_key=True)
    value = Column(Text, nullable=True)
    description = Column(Text, nullable=True)
    updated_at = Column(DateTime(timezone=True), default=utcnow, onupdate=utcnow, nullable=False)
